export const t = (lang: Lang) => (lang === "fr" ? fr : en);
export type StaffText = Dict;

/** "Wednesday 28 October" / "Mercredi 28 octobre" (no Intl, so server and browser match). */
export const longDate = (iso: string, lang: Lang) => {
  const d = new Date(`${iso}T00:00:00Z`);
  const x = t(lang);
  return `${x.days[d.getUTCDay()]} ${d.getUTCDate()} ${x.months[d.getUTCMonth()]}`;
};
export const shortDay = (iso: string, lang: Lang) => {
  const d = new Date(`${iso}T00:00:00Z`);
  const x = t(lang);
  return `${x.days[d.getUTCDay()].slice(0, 3)} ${d.getUTCDate()} ${x.monthsShort[d.getUTCMonth()]}`;
};
export const weekdayShort = (iso: string, lang: Lang) => t(lang).days[new Date(`${iso}T00:00:00Z`).getUTCDay()].slice(0, 3);
export const monthLabel = (month: string, lang: Lang) => {
  const name = t(lang).months[Number(month.slice(5, 7)) - 1];
  return `${name} ${month.slice(0, 4)}`;
};

export const greeting = (lang: Lang) => {
  const hour = Number(new Intl.DateTimeFormat("en-GB", { hour: "numeric", hourCycle: "h23", timeZone: "Indian/Mauritius" }).format(new Date()));
  const g = t(lang).greeting;
  return hour < 12 ? g.morning : hour < 18 ? g.afternoon : g.evening;
};
